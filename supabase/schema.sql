alter table public.matches enable row level security;
alter table public.bookings enable row level security;

grant select on public.matches to anon, authenticated;

drop policy if exists "Anyone can view matches" on public.matches;
create policy "Anyone can view matches"
  on public.matches for select
  to anon, authenticated
  using (true);

create or replace function public.book_ticket(p_match_id bigint)
returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  new_booking_id uuid;
begin
  update public.matches
  set available_seats = available_seats - 1
  where id = p_match_id and available_seats > 0;

  if not found then
    raise exception 'MATCH_SOLD_OUT_OR_NOT_FOUND';
  end if;

  insert into public.bookings (match_id)
  values (p_match_id)
  returning id into new_booking_id;

  return new_booking_id;
end;
$$;

revoke all on function public.book_ticket(bigint) from public;
grant execute on function public.book_ticket(bigint) to anon, authenticated;

do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'matches'
  ) then
    alter publication supabase_realtime add table public.matches;
  end if;
end;
$$;
